/** Browser acceptance against verify-ai-news.ts --serve only, never against real storage. */
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {chromium} from 'playwright';

const base=process.argv[2];assert.match(base??'',/^http:\/\/127\.0\.0\.1:\d+$/);
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const output='/tmp/douyin-ai-news-ui';await mkdir(output,{recursive:true});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
let checks=0;
try {
  await page.goto(base+'/hotspots');
  await page.getByRole('heading',{name:'今日头条热榜'}).waitFor();
  assert.equal(await page.getByRole('combobox',{name:'筛选来源'}).locator('option').count(),6);checks++;
  await page.getByRole('button',{name:'AI／科技资讯',exact:true}).click();
  await page.getByRole('heading',{name:'Microsoft Research官方 RSS'}).waitFor();
  assert.equal(await page.getByRole('combobox',{name:'筛选来源'}).locator('option').count(),4);checks++;
  assert.equal(await page.getByRole('heading',{name:'今日头条热榜'}).count(),0);checks++;
  const ms=page.locator('section').filter({has:page.getByRole('heading',{name:'Microsoft Research官方 RSS'})});
  assert.match(await ms.innerText(),/最新发布在前，序号不代表热度/);
  assert.ok(!(await ms.innerText()).includes('原始热度'));checks++;
  await page.screenshot({path:output+'/desktop.png',fullPage:true});
  const title='隔离验收选题 0 · Microsoft Research';
  const save=ms.getByRole('button',{name:'收藏：'+title,exact:true});if(await save.count())await save.click();
  await page.getByRole('button',{name:/选题收藏 \(1\)/}).click();
  await page.getByRole('button',{name:'查看详情：'+title,exact:true}).waitFor();
  assert.ok((await page.locator('main').innerText()).includes('发布于'));checks++;
  await page.getByRole('button',{name:'查看详情：'+title,exact:true}).click();
  const dialog=page.getByRole('dialog',{name:title,exact:true});
  await dialog.getByText('RSS 摘要（仅供参考，请读取原文核实）').waitFor();checks++;
  await dialog.getByRole('button',{name:'读取来源',exact:true}).click();
  await dialog.getByRole('checkbox',{name:'选择这份正文用于文章'}).check();
  await dialog.getByRole('button',{name:'用于文章创作',exact:true}).click();
  await page.waitForURL(/\/articles\/[a-f0-9-]+$/);
  await page.getByRole('button',{name:'资料与事实',exact:true}).click();
  await page.getByText('查看原始资料',{exact:true}).click();
  await page.getByText('这是隔离验收正文。',{exact:false}).first().waitFor();checks++;
  await page.goto(base+'/hotspots?tab=ai-tech&source=openai');
  await page.getByRole('heading',{name:'OpenAI官方 RSS'}).waitFor();
  await page.getByRole('button',{name:'以此创作公众号文章',exact:true}).first().click();
  await page.waitForURL(/\/articles\?.*sourceId=openai/);checks++;
  assert.equal(new URL(page.url()).searchParams.get('itemId'),'https://openai.com/news/qa-0');checks++;
  await page.goto(base+'/hotspots?tab=ai-tech&source=openai');
  await page.getByRole('button',{name:'平台热榜',exact:true}).click();
  await page.getByRole('heading',{name:'今日头条热榜'}).waitFor();
  assert.equal(await page.getByRole('combobox',{name:'筛选来源'}).inputValue(),'all');checks++;
  await page.setViewportSize({width:375,height:900});
  await page.getByRole('button',{name:'AI／科技资讯',exact:true}).click();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));checks++;
  await page.screenshot({path:output+'/mobile.png',fullPage:true});
  await page.getByRole('button',{name:'查看详情：'+title,exact:true}).click();
  await dialog.getByRole('button',{name:'读取来源',exact:true}).click();
  await dialog.getByRole('checkbox',{name:'选择这份正文用于文章'}).waitFor();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));checks++;
  await page.screenshot({path:output+'/mobile-detail.png'});
  assert.deepEqual(errors,[]);checks++;
  console.log(JSON.stringify({ok:true,checks,screenshots:output,realPublishing:false}));
} finally {await browser.close();}
